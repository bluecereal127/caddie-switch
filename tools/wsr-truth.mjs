// Per-hole truth data from the WSR collision meshes, expressed in the app's map
// frame (the 250x304 minimap, fractional coords) through tools/mesh-registration.json.
// The user's rule: when in doubt, WSR data is the truth and derived data adjusts
// to it. build-derived.mjs reads the output and uses it in place of the
// capture-derived scale, green box/outline, slope grid and tee.
//
//   node tools/wsr-truth.mjs [--meshes captures/meshes/wsr-kcl-obj] [--out tools/wsr-truth.json]
//
// Per hole:
//   scale      yd per map px (registration fit; 1 mesh unit = 0.1 m)
//   greenBox   bbox of the mesh green (KCL type 6) outline, map fractions
//   greenPoly  that outline, simplified (Douglas-Peucker, 0.25 map px)
//   tee        area-weighted centre of the flat tee pad; teePad the convex
//              hull of the pad's own triangles
//   grid       9x9 downhill slope vectors in the green-local frame (bbox-
//              normalized, +x right, +y down), built like extract-greens.mjs
//              (central differences of cell-mean heights, cells counted when
//              >12% of their samples are green, normalized to the green's own
//              steepest cell) but with physical spacing, so directions are
//              true on non-square greens
//   gridPct    the same vectors unnormalized, in percent slope (rise/run),
//              for calibrating the putt model later; slopeMaxPct, reliefYd
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseObj, groupBoundaryLoops, groupComponents, rasterizeHeight, triVerts } from "./lib/obj.mjs";

const args = process.argv.slice(2);
const opt = { meshes: "captures/meshes/wsr-kcl-obj", out: "tools/wsr-truth.json", names: "tools/mesh-holes.json", registration: "tools/mesh-registration.json" };
for (let i = 0; i < args.length; i++) {
  const a = args[i];
  if (a === "--meshes") opt.meshes = args[++i];
  else if (a === "--out") opt.out = args[++i];
}
const names = JSON.parse(readFileSync(opt.names, "utf8"));
const reg = JSON.parse(readFileSync(opt.registration, "utf8"));
const UPY = names.unitsPerYard || 9.144;
const W = 250, H = 304, GRID_N = 9;
const holeToMesh = {};
for (const [k, v] of Object.entries(names)) if (typeof v === "number" && !k.startsWith("_") && !["unitsPerYard", "metresPerUnit"].includes(k)) holeToMesh[v] = k;
const r4 = (v) => +v.toFixed(4);

// Douglas-Peucker on a closed ring (points in map px)
function simplifyRing(pts, eps) {
  if (pts.length < 8) return pts;
  // split the ring at its two farthest-apart points, simplify both halves
  let a = 0, b = 0, best = -1;
  for (let i = 0; i < pts.length; i++) { const d = Math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]); if (d > best) { best = d; b = i; } }
  const dp = (seg) => {
    if (seg.length < 3) return seg;
    const [p, q] = [seg[0], seg[seg.length - 1]];
    const L = Math.hypot(q[0] - p[0], q[1] - p[1]) || 1e-9;
    let far = -1, fd = -1;
    for (let i = 1; i < seg.length - 1; i++) {
      const d = Math.abs((q[0] - p[0]) * (p[1] - seg[i][1]) - (p[0] - seg[i][0]) * (q[1] - p[1])) / L;
      if (d > fd) { fd = d; far = i; }
    }
    if (fd <= eps) return [p, q];
    const left = dp(seg.slice(0, far + 1)), right = dp(seg.slice(far));
    return [...left.slice(0, -1), ...right];
  };
  const h1 = dp(pts.slice(a, b + 1)), h2 = dp([...pts.slice(b), pts[a]]);
  return [...h1.slice(0, -1), ...h2.slice(0, -1)];
}

const out = { _note: "WSR collision-mesh truth in the app's map frame (250x304 minimap, fractional coords). Generated by tools/wsr-truth.mjs from the meshes + tools/mesh-registration.json; consumed by tools/build-derived.mjs. grid = 9x9 [dx,dy] downhill, +x right +y down, normalized to the green's own steepest cell (extract-greens.mjs convention, physical spacing); gridPct = the same in percent slope.", unitsPerYard: UPY, holes: {} };

for (let hole = 1; hole <= 21; hole++) {
  const meshId = holeToMesh[hole];
  const R = reg.holes[hole];
  if (!meshId || !R) { console.log(`H${hole}: no mesh/registration`); continue; }
  const A = R.mapFracToMesh, B = R.meshToMapFrac;
  const toFrac = (X, Z) => [B[0][0] * X + B[0][1] * Z + B[0][2], B[1][0] * X + B[1][1] * Z + B[1][2]];
  const toMesh = (fx, fy) => [A[0][0] * fx + A[0][1] * fy + A[0][2], A[1][0] * fx + A[1][1] * fy + A[1][2]];
  const mesh = parseObj(join(opt.meshes, `WS2_glf_course_${meshId}.kcl.obj`));
  const gi = mesh.groups.findIndex((g) => g.type === 6 && g.tris > 0);
  const loops = groupBoundaryLoops(mesh, gi).filter((l) => l.perim > 50);
  const main = loops.slice().sort((a, b) => b.n - a.n)[0];

  // outline + box in map px
  const ring = main.pts.map(([X, , Z]) => { const [fx, fy] = toFrac(X, Z); return [fx * W, fy * H]; });
  let bx0 = Infinity, by0 = Infinity, bx1 = -Infinity, by1 = -Infinity;
  for (const [x, y] of ring) { bx0 = Math.min(bx0, x); bx1 = Math.max(bx1, x); by0 = Math.min(by0, y); by1 = Math.max(by1, y); }
  const greenBox = { x0: r4(bx0 / W), y0: r4(by0 / H), x1: r4(bx1 / W), y1: r4(by1 / H) };
  const poly = simplifyRing(ring, 0.25).map(([x, y]) => [r4(x / W), r4(y / H)]);

  // green heights: raster of type 6 only, 1 unit/px around the main loop
  const pad = 8;
  const rx0 = main.x0 - pad, rz0 = main.z0 - pad, rx1 = main.x1 + pad, rz1 = main.z1 + pad;
  const rw = Math.ceil(rx1 - rx0), rh = Math.ceil(rz1 - rz0);
  const include = new Uint8Array(mesh.groups.length); include[gi] = 1;
  const { height } = rasterizeHeight(mesh, { x0: rx0, z0: rz0, x1: rx0 + rw, z1: rz0 + rh, w: rw, h: rh, include });
  const hAt = (X, Z) => { const i = Math.floor(X - rx0), j = Math.floor(Z - rz0); if (i < 0 || j < 0 || i >= rw || j >= rh) return null; const v = height[j * rw + i]; return v === -Infinity ? null : v; };
  let hMin = Infinity, hMax = -Infinity;
  for (const v of height) if (v !== -Infinity) { hMin = Math.min(hMin, v); hMax = Math.max(hMax, v); }

  // cell-mean heights over the green-local 9x9 grid (sampled 12x12 per cell)
  const S = 12;
  const cellH = Array.from({ length: GRID_N }, () => new Array(GRID_N).fill(null));
  for (let gy = 0; gy < GRID_N; gy++) for (let gx = 0; gx < GRID_N; gx++) {
    let sum = 0, n = 0;
    for (let sy = 0; sy < S; sy++) for (let sx = 0; sx < S; sx++) {
      const fx = greenBox.x0 + ((gx + (sx + 0.5) / S) / GRID_N) * (greenBox.x1 - greenBox.x0);
      const fy = greenBox.y0 + ((gy + (sy + 0.5) / S) / GRID_N) * (greenBox.y1 - greenBox.y0);
      const [X, Z] = toMesh(fx, fy);
      const v = hAt(X, Z);
      if (v != null) { sum += v; n++; }
    }
    if (n > 0.12 * S * S) cellH[gy][gx] = sum / n / UPY; // yards
  }
  // physical cell spacing in yards (map px are isotropic under a similarity fit)
  const cwYd = ((greenBox.x1 - greenBox.x0) * W / GRID_N) * R.ydPerPx;
  const chYd = ((greenBox.y1 - greenBox.y0) * H / GRID_N) * R.ydPerPx;
  const at = (gy, gx) => (gy >= 0 && gy < GRID_N && gx >= 0 && gx < GRID_N) ? cellH[gy][gx] : null;
  const vec = Array.from({ length: GRID_N }, () => Array.from({ length: GRID_N }, () => null));
  let maxMag = 0, sumMag = 0, nMag = 0;
  for (let gy = 0; gy < GRID_N; gy++) for (let gx = 0; gx < GRID_N; gx++) {
    const c = cellH[gy][gx]; if (c == null) continue;
    const l = at(gy, gx - 1), rr = at(gy, gx + 1), u = at(gy - 1, gx), d = at(gy + 1, gx);
    const ddx = (rr != null && l != null) ? (rr - l) / (2 * cwYd) : (rr != null ? (rr - c) / cwYd : (l != null ? (c - l) / cwYd : 0));
    const ddy = (d != null && u != null) ? (d - u) / (2 * chYd) : (d != null ? (d - c) / chYd : (u != null ? (c - u) / chYd : 0));
    const vx = -ddx, vy = -ddy; // downhill, +y = map down (south)
    const m = Math.hypot(vx, vy);
    vec[gy][gx] = [vx, vy]; maxMag = Math.max(maxMag, m); sumMag += m; nMag++;
  }
  const grid = vec.map((row) => row.map((v) => (v && maxMag > 1e-9 ? [+(v[0] / maxMag).toFixed(3), +(v[1] / maxMag).toFixed(3)] : [0, 0])));
  const gridPct = vec.map((row) => row.map((v) => (v ? [+(v[0] * 100).toFixed(2), +(v[1] * 100).toFixed(2)] : [0, 0])));

  // tee pad: the small, perfectly flat fairway-class island farthest from the
  // green (fragments of one pad merged), as mesh-heightmap.mjs finds it; the
  // polygon is the convex hull of the pad's own triangles, not a rectangle
  let tee = null, teePad = null;
  {
    const fi = mesh.groups.findIndex((g) => g.type === 1 && g.tris > 0);
    const pads = fi < 0 ? [] : groupComponents(mesh, fi).filter((c) => c.w >= 20 && c.d >= 20 && c.w <= 300 && c.d <= 300 && c.y1 - c.y0 <= 0.6 && c.tris >= 4);
    if (pads.length) {
      pads.sort((a, b) => Math.hypot(b.cx - main.cx, b.cz - main.cz) - Math.hypot(a.cx - main.cx, a.cz - main.cz));
      const far = pads[0];
      const frags = pads.filter((p) => Math.hypot(p.cx - far.cx, p.cz - far.cz) < 250 && Math.abs(p.y0 - far.y0) < 0.6);
      const area = frags.reduce((s, p) => s + p.areaXZ, 0) || 1;
      const tx = frags.reduce((s, p) => s + p.cx * p.areaXZ, 0) / area, tz = frags.reduce((s, p) => s + p.cz * p.areaXZ, 0) / area;
      const [fx, fy] = toFrac(tx, tz);
      tee = { x: r4(fx), y: r4(fy) };
      const pts = [];
      const nt = mesh.tris.length / 3;
      for (let t = 0; t < nt; t++) {
        if (mesh.triGroup[t] !== fi) continue;
        const v = triVerts(mesh, t);
        const cx = (v[0] + v[3] + v[6]) / 3, cy = (v[1] + v[4] + v[7]) / 3, cz = (v[2] + v[5] + v[8]) / 3;
        if (Math.abs(cy - far.y0) > 0.6 || !frags.some((p) => cx >= p.x0 && cx <= p.x1 && cz >= p.z0 && cz <= p.z1)) continue;
        for (let k = 0; k < 9; k += 3) { const [px, py] = toFrac(v[k], v[k + 2]); pts.push([px * W, py * H]); }
      }
      // convex hull (monotone chain), map px -> fractions
      pts.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
      const cross = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
      const lower = [], upper = [];
      for (const p of pts) { while (lower.length >= 2 && cross(lower[lower.length - 2], lower[lower.length - 1], p) <= 0) lower.pop(); lower.push(p); }
      for (let i = pts.length - 1; i >= 0; i--) { const p = pts[i]; while (upper.length >= 2 && cross(upper[upper.length - 2], upper[upper.length - 1], p) <= 0) upper.pop(); upper.push(p); }
      teePad = [...lower.slice(0, -1), ...upper.slice(0, -1)].map(([x, y]) => [r4(x / W), r4(y / H)]);
    }
  }

  out.holes[hole] = {
    meshId, scale: R.ydPerPx, greenBox, greenPoly: poly,
    greenCentre: [r4((bx0 + bx1) / 2 / W), r4((by0 + by1) / 2 / H)],
    tee, teePad, grid, gridPct,
    slopeMaxPct: +(maxMag * 100).toFixed(2), slopeMeanPct: nMag ? +((sumMag / nMag) * 100).toFixed(2) : 0,
    reliefYd: +((hMax - hMin) / UPY).toFixed(2), greenCells: nMag,
  };
  console.log(`H${String(hole).padStart(2)} ${meshId.padEnd(7)} box ${(bx0).toFixed(1)},${(by0).toFixed(1)}..${(bx1).toFixed(1)},${(by1).toFixed(1)} px  poly ${ring.length}->${poly.length} pts  cells ${nMag}  slope max ${(maxMag * 100).toFixed(1)}% mean ${nMag ? ((sumMag / nMag) * 100).toFixed(1) : "-"}%  relief ${((hMax - hMin) / UPY).toFixed(2)} yd  tee ${tee ? `${(tee.x * W).toFixed(1)},${(tee.y * H).toFixed(1)}` : "-"}`);
}
writeFileSync(opt.out, JSON.stringify(out, null, 1));
console.log(`wrote ${opt.out}`);
